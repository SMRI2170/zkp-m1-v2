"""Verify native Groth16 artifacts against trusted local VKs before issuing a receipt.
Only proof/public are copied into the receive sandbox, never prior assignments or PKs.
"""
from pathlib import Path
import hashlib
import json
import os
import subprocess
import sys
import tempfile
import time

ROOT = Path(__file__).resolve().parents[3]
BINARY = ROOT / '.cache/week23/private-pcd-integrated'
# Receiver-owned trust anchor, never resolved relative to an untrusted packet.
WORK = ROOT / '.cache/week23/private/integrated-history-v1'
os.umask(0o077)

def canon(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'))

def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()

def receive(manifest_path, now=100002, session=777, policy=20261011):
    manifest = json.loads(Path(manifest_path).read_text())
    kind = manifest['kind']
    if kind not in ('individual', 'recursive'):
        raise ValueError('unknown proof kind')
    artifacts = manifest['artifacts']
    stages = [a['stage'] for a in artifacts]
    if stages != ([1, 2, 3] if kind == 'individual' else [3]):
        raise ValueError('missing or duplicate member')
    original = json.loads((ROOT / 'week23/manifests/sources.json').read_text())['research_sources_sha256']
    for name in ('main.go', 'relations.go', 'go.mod', 'go.sum'):
        if sha(ROOT / 'week23/poc/private-pcd' / name) != original['poc/private-pcd/' + name]:
            raise ValueError('circuit/dependency source mismatch; fixtures preserved')
    records = []
    started = time.monotonic()
    for artifact in artifacts:
        stage = artifact['stage']
        trusted = ROOT / '.cache/week23/private' / ('baseline' if kind == 'individual' else 'pcd') / str(stage) / 'vk.bin'
        # Trusted pins are generated by the local experiment authority; input cannot provide a VK.
        pins = json.loads((WORK / 'trusted-vks.json').read_text())
        if sha(trusted) != pins[kind + '-' + str(stage)]:
            raise ValueError('trusted VK mismatch')
        with tempfile.TemporaryDirectory(dir=WORK) as temp:
            out = Path(temp) / str(stage)
            out.mkdir(mode=0o700)
            for name in ('proof', 'public'):
                data = Path(artifact[name]).read_bytes()
                (out / (name + '.bin')).write_bytes(data)
            (out / 'vk.bin').symlink_to(trusted)
            proc = subprocess.run([str(BINARY), 'inspect-verified', temp, str(stage)], capture_output=True, text=True)
            if proc.returncode:
                raise ValueError('native Groth16 verification rejected')
            line = next(line for line in proc.stdout.splitlines() if line.startswith('{'))
            public = [int(v) for v in json.loads(line)['public']]
            if public[:5] != [1, session, 424242, 100001, policy]:
                raise ValueError('wrong proof session/policy/RID/bucket')
            if not public[3] <= now <= public[3] + 2:
                raise ValueError('expired/future observation (synthetic clock)')
            expected_mask = 1 << (stage - 1) if kind == 'individual' else 7
            if public[5] != expected_mask or public[8] != (1 if kind == 'individual' else 3) or sum(public[6:8]) != public[8]:
                raise ValueError('wrong membership/count')
            records.append({'stage': stage, 'proof_sha256': sha(out / 'proof.bin'), 'public_sha256': sha(out / 'public.bin'), 'vk_sha256': sha(trusted), 'public': public})
    receipt = {'domain': 'week23-offchain-verified-evidence-v1', 'protocol_version': 1,
               'kind': kind, 'proof_session': session, 'claimed_rid': 424242, 'bucket': 100001,
               'policy': policy, 'member_mask': 7, 'consistent': sum(r['public'][6] for r in records),
               'suspicious': sum(r['public'][7] for r in records), 'proof_status': 'VALID',
               'rid_auth_status': 'UNVERIFIED', 'physical_risk': 'UNKNOWN', 'evidence': records}
    encoded = canon(receipt)
    return {'receipt': receipt, 'canonical': encoded, 'sha256': hashlib.sha256(encoded.encode()).hexdigest(),
            'verify_ms': (time.monotonic() - started) * 1000, 'pid': os.getpid()}

if __name__ == '__main__':
    try:
        print(json.dumps(receive(sys.argv[1], *map(int, sys.argv[2:]))))
    except Exception as error:
        print(json.dumps({'rejected': True, 'reason': str(error)}))
        sys.exit(1)
