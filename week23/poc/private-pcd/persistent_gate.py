"""Fixed-roster local receive policy over real recursive proofs; synthetic clock only."""
from pathlib import Path
import base64
import hashlib
import json
import os
import sqlite3
import subprocess
import sys
import tempfile
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from signed_transport import canon, save

os.umask(0o077)
ROOT = Path(__file__).resolve().parents[3]
FIXTURES = ROOT / '.cache/week23/private/pcd'
TRANSPORT = ROOT / '.cache/week23/private/signed-transport'
WORK = ROOT / '.cache/week23/private/persistent-gate'
BINARY = ROOT / '.cache/week23/private-pcd-forks'


def receive(db, packet_path, now):
    packet = json.loads(Path(packet_path).read_text())
    body = packet['body']
    stage = body['stage']
    if stage not in (1, 2, 3):
        raise ValueError('unknown fixed-roster member')
    roster = json.loads((TRANSPORT / 'roster.json').read_text())
    Ed25519PublicKey.from_public_bytes(base64.b64decode(roster[str(stage)], validate=True)).verify(
        base64.b64decode(packet['signature'], validate=True), canon(body))
    if (body['session'], body['policy'], body['rid'], body['bucket']) != (777, 20261011, 424242, 100001):
        raise ValueError('wrong session/policy')
    if not body['bucket'] <= now <= body['bucket'] + 2:
        raise ValueError('expired/future')
    # VK is trusted local metadata, never supplied by the sender. The fixed stage
    # circuit pins the same session/policy/RID/bucket and cumulative member mask.
    with tempfile.TemporaryDirectory(dir=WORK) as temp:
        p = Path(temp) / str(stage)
        p.mkdir(mode=0o700)
        for name in ('proof', 'public'):
            save(p / (name + '.bin'), base64.b64decode(body[name], validate=True))
        (p / 'vk.bin').symlink_to(FIXTURES / str(stage) / 'vk.bin')
        result = subprocess.run([str(BINARY), 'verify', temp, str(stage)], capture_output=True)
        if result.returncode:
            raise ValueError('invalid native recursive proof')
    digest = hashlib.sha256(canon(packet)).hexdigest()
    con = sqlite3.connect(db, timeout=30)
    try:
        con.execute('CREATE TABLE IF NOT EXISTS received (session INTEGER, policy INTEGER, rid INTEGER, bucket INTEGER, stage INTEGER, digest TEXT, PRIMARY KEY(session,policy,rid,bucket,stage))')
        con.execute('BEGIN IMMEDIATE')
        key = (body['session'], body['policy'], body['rid'], body['bucket'])
        if stage == 1:
            if body['previous_packet_sha256'] is not None:
                raise ValueError('unexpected parent')
        else:
            prev = con.execute('SELECT digest FROM received WHERE session=? AND policy=? AND rid=? AND bucket=? AND stage=?', (*key, stage - 1)).fetchone()
            if prev is None or prev[0] != body['previous_packet_sha256']:
                raise ValueError('missing or different predecessor')
        try:
            con.execute('INSERT INTO received VALUES (?,?,?,?,?,?)', (*key, stage, digest))
        except sqlite3.IntegrityError:
            raise ValueError('replay or competing continuation')
        con.commit()
    finally:
        con.close()
    os.chmod(db, 0o600)
    return digest


def worker(db, packet, now):
    try:
        receive(db, packet, int(now))
    except Exception as error:
        return {'accepted': False, 'reason': type(error).__name__ + ': ' + str(error), 'pid': os.getpid()}
    return {'accepted': True, 'pid': os.getpid()}


def main():
    WORK.mkdir(mode=0o700)  # preserve previous attempts; fail if one already exists
    rows = []

    def call(db, packet, now=100002):
        command = [sys.executable, __file__, 'receive', str(db), str(packet), str(now)]
        return json.loads(subprocess.check_output(command, text=True))

    def record(case, result, expected):
        if result['accepted'] != expected:
            raise RuntimeError(case + ' unexpected result: ' + str(result))
        rows.append({'case': case, **result})

    packets = {stage: TRANSPORT / (str(stage) + '.json') for stage in (1, 2, 3)}
    db = WORK / 'restart.sqlite'
    for stage in (1, 2, 3):
        record('normal-stage-' + str(stage), call(db, packets[stage]), True)
    record('replay-after-process-restart', call(db, packets[3]), False)
    record('expired', call(WORK / 'expired.sqlite', packets[1], 100004), False)
    record('future', call(WORK / 'future.sqlite', packets[1], 100000), False)
    dropout = WORK / 'dropout.sqlite'
    record('dropout-A-received', call(dropout, packets[1]), True)
    record('B-dropout-C-cannot-continue', call(dropout, packets[3]), False)

    # Both alternative C proofs were generated by separate prover processes.
    # Their signed envelopes share the accepted B parent. No prior assignment is read.
    from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey
    key = Ed25519PrivateKey.from_private_bytes((TRANSPORT / '3.key').read_bytes())
    alternatives = []
    original = json.loads(packets[3].read_text())
    for variant in ('normal', 'outlier'):
        body = dict(original['body'])
        for name in ('proof', 'public'):
            body[name] = base64.b64encode((ROOT / '.cache/week23/private' / ('pcd-fork-' + variant) / (name + '.bin')).read_bytes()).decode()
        packet = {'body': body, 'signature': base64.b64encode(key.sign(canon(body))).decode()}
        path = WORK / (variant + '.json')
        save(path, canon(packet))
        alternatives.append(path)

    race_db = WORK / 'concurrent.sqlite'
    for stage in (1, 2):
        record('concurrent-parent-' + str(stage), call(race_db, packets[stage]), True)
    workers = [subprocess.Popen([sys.executable, __file__, 'receive', str(race_db), str(p), '100002'], stdout=subprocess.PIPE, text=True) for p in alternatives]
    race = [json.loads(p.communicate()[0]) for p in workers]
    if sum(r['accepted'] for r in race) != 1:
        raise RuntimeError('transactional conflict gate failed')
    rows.append({'case': 'two-concurrent-C-submissions', 'workers': race, 'accepted_count': 1})
    # Independent hosts can select different valid histories: a local SQLite lock
    # is not consensus, and does not provide global fork/replay protection.
    for i, packet in enumerate(alternatives):
        independent = WORK / ('independent-' + str(i) + '.sqlite')
        for stage in (1, 2):
            if not call(independent, packets[stage])['accepted']:
                raise RuntimeError('independent parent failed')
        record('independent-host-branch-' + str(i), call(independent, packet), True)
    result = {'tests': rows, 'clock': 'synthetic', 'scope': 'fixed trusted roster/VKs, actual native proof verification, host-local durable policy; independent hosts can fork', 'private_assignment_transferred': False}
    (ROOT / 'week23/logs/private-pcd-persistent-gate.json').write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result))


if __name__ == '__main__':
    if len(sys.argv) == 5 and sys.argv[1] == 'receive':
        print(json.dumps(worker(*sys.argv[2:])))
    else:
        main()
