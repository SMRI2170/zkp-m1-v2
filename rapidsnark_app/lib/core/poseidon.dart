const _nRoundsF = 8;   // フルラウンド数（前半4 + 後半4）
const _nRoundsP = 57;  // パーシャルラウンド数（t=3 の場合）
const _t = 3;

/// BN254 Poseidon ハッシュ（入力2個、t=3）
///
/// 入力2個の BN254 フィールド要素を受け取り、ハッシュ値を返す。
/// circomlib の poseidon(a, b) と同じ結果を生成する（定数が正しければ）。
///
/// TODO: verify round constants against circomlibjs poseidon_constants_opt.js
BigInt poseidon2(BigInt a, BigInt b) {
  // 初期状態: [capacity=0, a, b]
  var state = [BigInt.zero, a % _p, b % _p];

  var cIndex = 0;

  // フルラウンド（前半 nRoundsF/2 = 4 回）
  for (var r = 0; r < _nRoundsF ~/ 2; r++) {
    for (var i = 0; i < _t; i++) {
      state[i] = (state[i] + _C[cIndex++]) % _p;
    }
    for (var i = 0; i < _t; i++) {
      state[i] = _sbox(state[i]);
    }
    state = _mds(state);
  }

  // パーシャルラウンド（nRoundsP = 57 回）
  for (var r = 0; r < _nRoundsP; r++) {
    for (var i = 0; i < _t; i++) {
      state[i] = (state[i] + _C[cIndex++]) % _p;
    }
    state[0] = _sbox(state[0]);
    state = _mds(state);
  }

  // フルラウンド（後半 nRoundsF/2 = 4 回）
  for (var r = 0; r < _nRoundsF ~/ 2; r++) {
    for (var i = 0; i < _t; i++) {
      state[i] = (state[i] + _C[cIndex++]) % _p;
    }
    for (var i = 0; i < _t; i++) {
      state[i] = _sbox(state[i]);
    }
    state = _mds(state);
  }

  // 出力は state[1]（circomlib 準拠）
  return state[1];
}

/// BigInt を hi（上位127bit）と lo（下位127bit）に分割する。
/// ZK 回路の frame_commitment_hi/lo 入力として使用。
(BigInt hi, BigInt lo) splitHiLo(BigInt x) {
  final mask = (BigInt.one << 127) - BigInt.one;
  final lo = x & mask;
  final hi = x >> 127;
  return (hi, lo);
}
