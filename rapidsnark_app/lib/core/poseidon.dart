// ── 内部関数 ─────────────────────────────────────────────────────────────────

BigInt _sbox(BigInt x) {
  // x^5 mod p
  final x2 = (x * x) % _p;
  final x4 = (x2 * x2) % _p;
  return (x4 * x) % _p;
}

List<BigInt> _mds(List<BigInt> state) {
  final result = [BigInt.zero, BigInt.zero, BigInt.zero];
  for (var i = 0; i < 3; i++) {
    var sum = BigInt.zero;
    for (var j = 0; j < 3; j++) {
      sum = (sum + _M[i][j] * state[j]) % _p;
    }
    result[i] = sum;
  }
  return result;
}

